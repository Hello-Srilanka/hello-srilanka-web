    assert.ok(await narrow.locator('.export-previews figure').count() >= 3, '21-day trip splits into multiple images');
    const draws = await narrow.evaluate(() => window.exportDraws);
    assert.ok(draws.some(d => d.text.startsWith('DAY 21')), 'Every day reaches the export');
    assert.ok(draws.every(d => d.width <= 1241 && d.y < 1920 && d.x >= 100), 'All text fits inside PNG bounds');
