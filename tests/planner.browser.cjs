    const longResponse = await context.request.post(base + '/api/itinerary', { data: { id: crypto.randomUUID(), preferences: { ...request.preferences, duration: 21 } } });
    const longTrip = await parse(longResponse); assert.equal(longTrip.days.length, 21);
    const edge = await browser.newContext({ viewport: { width: 320, height: 740 }, acceptDownloads: true, reducedMotion: 'reduce' });
    await edge.route('**/*', route => /\.(woff2?|webp)(\?|$)/.test(route.request().url()) ? route.abort() : route.continue());
    await edge.addInitScript(({ trip, key }) => {
      localStorage.setItem(key, JSON.stringify({ preferences: trip.preferences, itinerary: trip, step: 4, screen: 'result', requestId: null }));
      window.exportDraws = [];
      const original = CanvasRenderingContext2D.prototype.fillText;
      CanvasRenderingContext2D.prototype.fillText = function(text, x, y, ...rest) {
        if (this.canvas.width === 1440) window.exportDraws.push({ text, x, y, width: this.measureText(text).width });
        return original.call(this, text, x, y, ...rest);
      };
    }, { trip: longTrip, key: 'hellosrilanka-planner-v1' });
    const narrow = await edge.newPage();
    await narrow.goto(base + '/plan'); await narrow.locator('#result-heading').waitFor();
    assert.ok(await narrow.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No 320px overflow');
