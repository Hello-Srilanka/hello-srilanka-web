    const [a, b] = await Promise.all([context.request.post(base + '/api/itinerary', { data: request }), context.request.post(base + '/api/itinerary', { data: request })]);
    const parse = async r => (await r.text()).trim().split('\n').map(s => JSON.parse(s)).find(e => e.result)?.result;
